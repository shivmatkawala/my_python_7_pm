# Datatypes:

    # Types of Data covered in this course:

        # Primitive Datatypes
            # Number:
                # Integer: 
                        # A number without decimal point
                        # Including 0
                        # Can be +ve or -ve
                        # 78, 90,-55, 0, 0, -100

                # Float:
                        # A number with Decimal point
                        # Can be +ve or -ve
                        # -0.0, 0.0, 67.000, 45.5656, 1.2121, -4.9087

                # Complex:
                        # A number is a combination of:
                                                # Real Number:  
                                                    # All Integers and Floats are Real Numbers
                                                    # Ex: 6, -78, -12.00, 7.091, -23.56

                                                # Imaginary Number:
                                                    # √-1 = j
                                                    # A number suffixed by j is imaginary number
                                                    # 67J, -12J, 0.567J, -90.123J
                        # Ex: 6+8j, 9-12j, -4-5j, -12.34+56.78j

            # Boolean:
                # True   ==> 1
                # False  ==> 0

            # Text:
                # String:
                    # Any type of charecters sequence enclosed by quotes are nothing but strings.
                    # Types of quotes used to create string:
                        # If String is small / single line
                        # ''   => Single quote
                        # ""   => Double Quote
                        # 'Hari is the "tallest" among all students in ACS.'
                        # "Hari is the 'tallest' among all students in ACS.""


                        # If your string is big / multiline string
                        # ''' ''' => Tripple Single Quote
                        # """ """ => Tripple Double Quote
                        # ''' 
                        #     Krishna Asked """ Where are you going Radha ?"""
                        #     Radha Replied """ Kanha I am going to Vrindavan"""
                        #     Krishna Asked """ Radha Shall I come with you ?"""
                        # '''


